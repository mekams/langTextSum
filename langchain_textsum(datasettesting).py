    # Preprocess the text
    preprocessed_chunks = preprocess_text(article)
    print(f"\nProcessing article {i + 1}...")

    # Summarize each chunk
    final_summaries = []
    for chunk in preprocessed_chunks:
        summary = summarization_pipeline(chunk)
        final_summaries.append(summary)

    # Combine summaries
    final_summary = " ".join(final_summaries)
