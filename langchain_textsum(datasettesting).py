# Preprocessing: Splitting text using LangChain's CharacterTextSplitter
def preprocess_text(text, chunk_size=7000, chunk_overlap=2500):
    splitter = CharacterTextSplitter(
        separator="\n",
        chunk_size=chunk_size,
        chunk_overlap=chunk_overlap
    )
    return splitter.split_text(text)

# Extractive Summarization: LexRank implementation
def extractive_summarization(text, num_sentences=20):
    parser = PlaintextParser.from_string(text, Tokenizer("english"))
    summarizer = LexRankSummarizer()
    summary = summarizer(parser.document, num_sentences)
    return " ".join([str(sentence) for sentence in summary])

# Abstractive Summarization using LangChain (Facebook BART)
prompt = PromptTemplate(
    input_variables=["text"],
    template="Provide a detailed and comprehensive summary of the following text: {text}"
)

# Hugging Face BART (Parameters)
llm = HuggingFaceHub(
    repo_id="facebook/bart-large-cnn",  # Specify the model repository
    task="summarization",
    huggingfacehub_api_token="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",  # Private Hugging Face token (Kamran Mustafa)
    model_kwargs={
        "max_length": 499,  # Max length of the generated summary
        "min_length": 20,   # Min length of the generated summary
        "num_beams": 6,      # beam search
        "length_penalty": 1.0  # Balanced Summary (neither long nor very short)
    }
)

llm_chain = LLMChain(prompt=prompt, llm=llm)

# Abstractive Summarization with LangChain
def abstractive_summarization_langchain(text):
    summary = llm_chain.run({"text": text})
    return summary

# LangChain Pipeline: Combining LexRank and LangChain-based BART summarization
def summarization_pipeline(text, lexrank_sentences=10):
    # Step 1: Extractive Summarization with LexRank
    lexrank_summary = extractive_summarization(text, num_sentences=lexrank_sentences)

    # Step 2: Abstractive Summarization with LangChain (BART)
    bart_summary = abstractive_summarization_langchain(lexrank_summary)
    return bart_summary

# ROUGE Score Calculation
def calculate_rouge(reference, generated):
    scorer = rouge_scorer.RougeScorer(["rouge1", "rouge2", "rougeL"], use_stemmer=True)
    scores = scorer.score(reference, generated)
    return scores

