def plot_rouge_scores(rouge_scores):
    metrics = list(rouge_scores.keys())
    precision = [score.precision for score in rouge_scores.values()]
    recall = [score.recall for score in rouge_scores.values()]
    f1 = [score.fmeasure for score in rouge_scores.values()]

    x = range(len(metrics))

    plt.figure(figsize=(10, 6))  # Adjust figure size as needed
    plt.bar(x, precision, width=0.2, label='Precision')
    plt.bar([i + 0.2 for i in x], recall, width=0.2, label='Recall')
    plt.bar([i + 0.4 for i in x], f1, width=0.2, label='F1-Score')

    plt.xlabel("ROUGE Metrics")
    plt.ylabel("Scores")
    plt.title("ROUGE Scores for Summary")
    plt.xticks([i + 0.2 for i in x], metrics)  # Center x-axis labels
    plt.legend()
    plt.tight_layout()
    plt.show()

